/// A user supplied, Microsoft SSML compatible speech endpoint.
///
/// Everything here is optional: an empty or half filled configuration simply
/// reports [CustomSpeechSettings.config] as null, so ordinary playback keeps
/// working with the built in voices.
const customSpeechStorageKey = 'listening.customSpeech.v1';
const defaultCustomSpeechAuthHeader = 'Ocp-Apim-Subscription-Key';
const defaultCustomSpeechOutputFormat = 'audio-24khz-48kbitrate-mono-mp3';
const customSpeechMinimumRatePercent = -50;
const customSpeechMaximumRatePercent = 100;
const customSpeechMaximumAudioBytes = 8 * 1024 * 1024;

String _text(Object? value) => value is String ? value.trim() : '';

int _percent(Object? value) {
  final number = value is num
      ? value.round()
      : int.tryParse(_text(value)) ?? 0;
  return number
      .clamp(customSpeechMinimumRatePercent, customSpeechMaximumRatePercent)
      .toInt();
}

Uri? _endpoint(String url) {
  final raw = url.trim();
  if (raw.isEmpty) return null;
  final uri = Uri.tryParse(raw);
  if (uri == null || uri.host.isEmpty) return null;
  if (uri.scheme != 'http' && uri.scheme != 'https') return null;
  return uri;
}

/// Normalize a BCP-47 style tag without rejecting the user's spelling outright.
String _locale(String value) {
  final parts = value
      .trim()
      .replaceAll('_', '-')
      .split('-')
      .where((part) => part.isNotEmpty)
      .toList();
  if (parts.isEmpty || !RegExp(r'^[a-zA-Z]{2,3}$').hasMatch(parts.first)) {
    return '';
  }
  final result = <String>[parts.first.toLowerCase()];
  for (final part in parts.skip(1)) {
    if (!RegExp(r'^[a-zA-Z0-9]{2,8}$').hasMatch(part)) return '';
    result.add(switch (part.length) {
      2 || 3 => part.toUpperCase(),
      4 => '${part[0].toUpperCase()}${part.substring(1).toLowerCase()}',
      _ => part,
    });
  }
  return result.join('-');
}

/// Immutable, fully validated view of a custom speech endpoint.
class CustomSpeechConfig {
  const CustomSpeechConfig({
    required this.url,
    required this.key,
    required this.voiceId,
    required this.locale,
    this.label = '',
    this.rate = 0,
    this.authHeader = defaultCustomSpeechAuthHeader,
    this.outputFormat = defaultCustomSpeechOutputFormat,
  });

  /// Returns null unless the endpoint address, key, voice and language are all
  /// usable, so callers never have to validate twice.
  static CustomSpeechConfig? tryCreate({
    required String url,
    required String key,
    required String voiceId,
    required String locale,
    String label = '',
    int rate = 0,
    String authHeader = defaultCustomSpeechAuthHeader,
    String outputFormat = defaultCustomSpeechOutputFormat,
  }) {
    final target = _endpoint(url);
    final voice = voiceId.trim();
    final language = _locale(locale);
    if (target == null ||
        key.trim().isEmpty ||
        voice.isEmpty ||
        language.isEmpty ||
        voice.length > 120 ||
        RegExp(r'''[\s<>&"']''').hasMatch(voice)) {
      return null;
    }
    return CustomSpeechConfig(
      url: target.toString(),
      key: key.trim(),
      voiceId: voice,
      locale: language,
      label: label.trim(),
      rate: _percent(rate),
      authHeader: _text(authHeader).isEmpty
          ? defaultCustomSpeechAuthHeader
          : _text(authHeader),
      outputFormat: _text(outputFormat).isEmpty
          ? defaultCustomSpeechOutputFormat
          : _text(outputFormat),
    );
  }

  final String url, key, voiceId, locale, label, authHeader, outputFormat;
  final int rate;

  Uri? get endpoint => _endpoint(url);

  /// Cache identity: the configured host, so switching endpoints cannot reuse
  /// audio that was generated by a different service.
  String get namespace {
    final host = endpoint?.host.toLowerCase() ?? '';
    return host.isEmpty ? 'custom' : host;
  }

  String get displayLabel => label.isEmpty ? voiceId : label;

  SpeechVoice get voice => SpeechVoice(
    id: voiceId,
    label: displayLabel,
    source: ListeningSource.custom,
    locale: locale,
    engine: namespace,
    quality: 1,
  );

  bool get usable =>
      endpoint != null &&
      key.isNotEmpty &&
      voiceId.isNotEmpty &&
      locale.isNotEmpty;

  String get rateLabel => rate == 0 ? '正常语速' : '${rate > 0 ? '+' : ''}$rate%';

  Map<String, Object> toJson() => {
    'url': url,
    'key': key,
    'voiceId': voiceId,
    'locale': locale,
    'label': label,
    'rate': rate,
    'authHeader': authHeader,
    'outputFormat': outputFormat,
  };

  factory CustomSpeechConfig.fromJson(Map<dynamic, dynamic> json) {
    final header = _text(json['authHeader']);
    final format = _text(json['outputFormat']);
    return CustomSpeechConfig(
      url: _text(json['url']),
      key: _text(json['key']),
      voiceId: _text(json['voiceId']),
      locale: _locale(_text(json['locale'])),
      label: _text(json['label']),
      rate: _percent(json['rate']),
      authHeader: header.isEmpty ? defaultCustomSpeechAuthHeader : header,
      outputFormat: format.isEmpty ? defaultCustomSpeechOutputFormat : format,
    );
  }

  CustomSpeechConfig copyWith({
    String? url,
    String? key,
    String? voiceId,
    String? locale,
    String? label,
    int? rate,
    String? authHeader,
    String? outputFormat,
  }) => CustomSpeechConfig(
    url: url ?? this.url,
    key: key ?? this.key,
    voiceId: voiceId ?? this.voiceId,
    locale: locale ?? this.locale,
    label: label ?? this.label,
    rate: _percent(rate ?? this.rate),
    authHeader: authHeader ?? this.authHeader,
    outputFormat: outputFormat ?? this.outputFormat,
  );

  @override
  bool operator ==(Object other) =>
      other is CustomSpeechConfig &&
      other.url == url &&
      other.key == key &&
      other.voiceId == voiceId &&
      other.locale == locale &&
      other.label == label &&
      other.rate == rate &&
      other.authHeader == authHeader &&
      other.outputFormat == outputFormat;

  @override
  int get hashCode => Object.hash(
    url,
    key,
    voiceId,
    locale,
    label,
    rate,
    authHeader,
    outputFormat,
  );

  @override
  String toString() =>
      'CustomSpeechConfig($namespace, $voiceId, $locale, ${rate}%)';
}

/// Persisted, observable endpoint settings. Listening reads [config] while the
/// settings page edits the same instance, so no extra copy has to be kept.
class CustomSpeechSettings extends ChangeNotifier {
  CustomSpeechSettings({
    String url = '',
    String key = '',
    String voiceId = '',
    String locale = 'zh-CN',
    String label = '',
    int rate = 0,
    String authHeader = defaultCustomSpeechAuthHeader,
    String outputFormat = defaultCustomSpeechOutputFormat,
  }) : _url = url,
       _key = key,
       _voiceId = voiceId,
       _locale = locale,
       _label = label,
       _rate = _percent(rate),
       _authHeader = authHeader,
       _outputFormat = outputFormat;

  String _url, _key, _voiceId, _locale, _label, _authHeader, _outputFormat;
  int _rate;

  String get url => _url;
  String get key => _key;
  String get voiceId => _voiceId;
  String get locale => _locale;
  String get label => _label;
  int get rate => _rate;
  String get authHeader => _authHeader;
  String get outputFormat => _outputFormat;

  bool get configured => config != null;

  /// The usable endpoint, or null while the settings are still incomplete.
  CustomSpeechConfig? get config => CustomSpeechConfig.tryCreate(
    url: _url,
    key: _key,
    voiceId: _voiceId,
    locale: _locale,
    label: _label,
    rate: _rate,
    authHeader: _authHeader,
    outputFormat: _outputFormat,
  );

  SpeechVoice? get voice => config?.voice;

  /// SharedPreferences is optional state; a damaged record never escapes.
  Future<void> load() async {
    try {
      final preferences = await SharedPreferences.getInstance();
      final raw = preferences.getString(customSpeechStorageKey);
      if (raw == null || raw.isEmpty) return;
      final decoded = jsonDecode(raw);
      if (decoded is! Map) return;
      _adopt(CustomSpeechConfig.fromJson(decoded));
    } catch (_) {
      /* Keep the built in voices usable with an unreadable endpoint record. */
    }
  }

  Future<void> save() async {
    final preferences = await SharedPreferences.getInstance();
    final saved = await preferences.setString(
      customSpeechStorageKey,
      jsonEncode(toJson()),
    );
    if (!saved) throw const SpeechFailure('自定义语音接口设置保存失败');
  }

  Future<void> apply(CustomSpeechConfig value) async {
    _adopt(value);
    await save();
  }

  Future<void> reset() async {
    _url = '';
    _key = '';
    _voiceId = '';
    _locale = 'zh-CN';
    _label = '';
    _rate = 0;
    _authHeader = defaultCustomSpeechAuthHeader;
    _outputFormat = defaultCustomSpeechOutputFormat;
    notifyListeners();
    try {
      final preferences = await SharedPreferences.getInstance();
      await preferences.remove(customSpeechStorageKey);
    } catch (_) {
      /* Clearing an optional endpoint stays best effort. */
    }
  }

  Map<String, Object> toJson() => {
    'url': _url,
    'key': _key,
    'voiceId': _voiceId,
    'locale': _locale,
    'label': _label,
    'rate': _rate,
    'authHeader': _authHeader,
    'outputFormat': _outputFormat,
  };

  void _adopt(CustomSpeechConfig value) {
    _url = value.url;
    _key = value.key;
    _voiceId = value.voiceId;
    _locale = value.locale;
    _label = value.label;
    _rate = _percent(value.rate);
    _authHeader = value.authHeader;
    _outputFormat = value.outputFormat;
    notifyListeners();
  }
}

String _escapeXml(String source) => source
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&apos;');

String _ssml(String spoken, CustomSpeechConfig config) {
  final rate = config.rate;
  final rateText = rate == 0 ? '+0%' : '${rate > 0 ? '+' : ''}$rate%';
  return '<speak version="1.0" xmlns="http://www.w3.org/2001/10/synthesis" '
      'xml:lang="${_escapeXml(config.locale)}">'
      '<voice name="${_escapeXml(config.voiceId)}">'
      '<prosody pitch="+0Hz" rate="$rateText" volume="+0%">'
      '${_escapeXml(spoken)}'
      '</prosody></voice></speak>';
}

/// Synthesises one segment through the configured endpoint and returns the
/// encoded audio bytes (mp3 by default) exactly like the built in clients.
class CustomSpeechClient {
  CustomSpeechClient({
    this.connectionTimeout = const Duration(seconds: 10),
    this.requestTimeout = const Duration(seconds: 40),
  });

  final Duration connectionTimeout, requestTimeout;

  Future<Uint8List> synthesize(
    String text,
    CustomSpeechConfig config,
    SpeechCancellation cancellation,
  ) async {
    final spoken = speechText(text);
    if (!hasSpeechText(spoken)) {
      throw const SpeechFailure(
        '这一段没有可朗读的文本',
        kind: SpeechFailureKind.content,
      );
    }
    final endpoint = config.endpoint;
    if (endpoint == null || !config.usable) {
      throw const SpeechFailure('自定义语音接口配置不完整，请重新填写');
    }
    cancellation.check();
    final client = HttpClient()
      ..userAgent = null
      ..connectionTimeout = connectionTimeout;
    final removeCancellation = cancellation.onCancel(
      () => client.close(force: true),
    );
    try {
      final request = await client.postUrl(endpoint).timeout(requestTimeout);
      final body = utf8.encode(_ssml(spoken, config));
      request.headers.set(
        HttpHeaders.contentTypeHeader,
        'application/ssml+xml; charset=utf-8',
      );
      request.headers.set(
        HttpHeaders.acceptHeader,
        'audio/mpeg, audio/wav, application/json',
      );
      request.headers.set(config.authHeader, config.key);
      request.headers.set('X-Microsoft-OutputFormat', config.outputFormat);
      request.contentLength = body.length;
      request.add(body);
      cancellation.check();
      final response = await request.close().timeout(requestTimeout);
      final builder = BytesBuilder(copy: false);
      await for (final chunk in response.timeout(requestTimeout)) {
        cancellation.check();
        builder.add(chunk);
        if (builder.length > customSpeechMaximumAudioBytes) {
          throw const SpeechFailure('单段自定义语音超过缓存上限');
        }
      }
      cancellation.check();
      final payload = builder.takeBytes();
      if (response.statusCode < 200 || response.statusCode >= 300) {
        throw SpeechFailure(
          _failureMessage(payload, response.statusCode),
          kind: response.statusCode >= 500 || response.statusCode == 429
              ? SpeechFailureKind.timeout
              : SpeechFailureKind.unavailable,
        );
      }
      final audio = _audioPayload(payload, response.headers.contentType);
      if (audio.length < 100) {
        throw const SpeechFailure(
          '自定义语音接口未返回音频',
          kind: SpeechFailureKind.content,
        );
      }
      return audio;
    } on SpeechCancelled {
      rethrow;
    } on SpeechFailure {
      rethrow;
    } on TimeoutException {
      cancellation.check();
      throw const SpeechFailure(
        '自定义语音接口响应超时，请稍后重试',
        kind: SpeechFailureKind.timeout,
      );
    } on HandshakeException {
      cancellation.check();
      throw const SpeechFailure('自定义语音接口安全连接失败，请检查证书与地址');
    } on SocketException {
      cancellation.check();
      throw const SpeechFailure('自定义语音接口连接失败，请检查网络与接口地址');
    } on HttpException {
      cancellation.check();
      throw const SpeechFailure('自定义语音接口返回异常，请检查接口地址');
    } catch (_) {
      cancellation.check();
      throw const SpeechFailure('自定义语音接口暂不可用，请检查配置');
    } finally {
      removeCancellation();
      client.close(force: true);
    }
  }
}

String _failureMessage(Uint8List payload, int status) {
  final detail = _readError(payload);
  if (detail.isEmpty) return '自定义语音接口返回 HTTP $status';
  final trimmed = detail.length > 160 ? '${detail.substring(0, 160)}…' : detail;
  return '自定义语音接口返回 HTTP $status：$trimmed';
}

String _readError(Uint8List payload) {
  if (payload.isEmpty) return '';
  try {
    final decoded = jsonDecode(utf8.decode(payload, allowMalformed: true));
    if (decoded is Map) {
      final error = decoded['error'];
      if (error is Map && error['message'] is String) {
        return (error['message'] as String).trim();
      }
      if (decoded['message'] is String) {
        return (decoded['message'] as String).trim();
      }
      if (decoded['detail'] is String) {
        return (decoded['detail'] as String).trim();
      }
      if (error is String) return error.trim();
    }
  } catch (_) {
    /* Not JSON: fall back to the raw text below. */
  }
  try {
    return utf8.decode(payload, allowMalformed: true).trim();
  } catch (_) {
    return '';
  }
}

/// Most services answer raw audio; JSON wrappers carry base64 instead.
Uint8List _audioPayload(Uint8List payload, ContentType? type) {
  final mime = type?.mimeType.toLowerCase() ?? '';
  final looksJson =
      mime.contains('json') || (payload.isNotEmpty && payload.first == 0x7B);
  if (!looksJson) return payload;
  try {
    final decoded = jsonDecode(utf8.decode(payload, allowMalformed: true));
    if (decoded is Map) {
      for (final key in const [
        'audio',
        'audioContent',
        'audio_content',
        'data',
        'result',
        'base64',
      ]) {
        final encoded = decoded[key];
        if (encoded is String && encoded.trim().isNotEmpty) {
          try {
            return base64Decode(encoded.trim());
          } catch (_) {
            /* Keep looking for a usable payload. */
          }
        }
        if (encoded is Map) {
          final nested = encoded['audio'] ?? encoded['content'];
          if (nested is String && nested.trim().isNotEmpty) {
            try {
              return base64Decode(nested.trim());
            } catch (_) {
              /* Keep looking for a usable payload. */
            }
          }
        }
      }
      final message = decoded['message'] ?? decoded['detail'];
      if (message is String && message.trim().isNotEmpty) {
        throw SpeechFailure('自定义语音接口返回：${message.trim()}');
      }
    }
  } on SpeechFailure {
    rethrow;
  } catch (_) {
    /* Unreadable JSON is returned verbatim; the caller validates the size. */
  }
  return payload;
}
